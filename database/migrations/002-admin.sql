CREATE TABLE IF NOT EXISTS settings (
 setting_key VARCHAR(100) PRIMARY KEY, value_json JSON NOT NULL, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS admins (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, email VARCHAR(254) UNIQUE NOT NULL,
 password_hash VARCHAR(255) NOT NULL, role VARCHAR(30) NOT NULL DEFAULT 'operator', active BOOLEAN NOT NULL DEFAULT TRUE,
 session_version INT NOT NULL DEFAULT 1, last_login_at DATETIME NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, admin_id BIGINT NULL, action VARCHAR(100) NOT NULL, entity_type VARCHAR(60) NOT NULL,
 entity_id VARCHAR(100) NOT NULL, details_json JSON NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX (entity_type, entity_id), INDEX (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS request_history (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, entity_type VARCHAR(30) NOT NULL, entity_id BIGINT NOT NULL,
 from_status VARCHAR(40) NULL, to_status VARCHAR(40) NOT NULL, admin_id BIGINT NULL, reason TEXT NOT NULL,
 details_json JSON NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX (entity_type, entity_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS admin_notes (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, entity_type VARCHAR(30) NOT NULL, entity_id BIGINT NOT NULL,
 admin_id BIGINT NOT NULL, note TEXT NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX (entity_type, entity_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS availability_rules (
 id VARCHAR(64) PRIMARY KEY, weekday INT NOT NULL, opens_at TIME NOT NULL, closes_at TIME NOT NULL,
 interval_minutes INT NOT NULL DEFAULT 30, capacity INT NOT NULL DEFAULT 1, active BOOLEAN NOT NULL DEFAULT TRUE,
 deleted_at DATETIME NULL, version INT NOT NULL DEFAULT 1, CHECK (weekday BETWEEN 1 AND 7), CHECK (capacity > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS add_on_price_overrides (
 id VARCHAR(64) PRIMARY KEY, add_on_id VARCHAR(64) NOT NULL, class_id VARCHAR(64) NOT NULL, price_minor INT NOT NULL,
 deleted_at DATETIME NULL, version INT NOT NULL DEFAULT 1, UNIQUE KEY addon_class (add_on_id,class_id),
 FOREIGN KEY (add_on_id) REFERENCES add_ons(id), FOREIGN KEY (class_id) REFERENCES vehicle_classes(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS site_content (
 id VARCHAR(100) PRIMARY KEY, title VARCHAR(200) NOT NULL, meta_title VARCHAR(200) NOT NULL, meta_description VARCHAR(320) NOT NULL,
 heading VARCHAR(250) NOT NULL, summary TEXT NOT NULL, body MEDIUMTEXT NOT NULL, image_path VARCHAR(250) NOT NULL DEFAULT '',
 published BOOLEAN NOT NULL DEFAULT TRUE, version INT NOT NULL DEFAULT 1, deleted_at DATETIME NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS media (
 id VARCHAR(64) PRIMARY KEY, name VARCHAR(200) NOT NULL, path VARCHAR(250) UNIQUE NOT NULL, alt_text VARCHAR(300) NOT NULL DEFAULT '',
 mime_type VARCHAR(40) NOT NULL, size_bytes INT NOT NULL, width INT NOT NULL, height INT NOT NULL,
 deleted_at DATETIME NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, version INT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS faqs (
 id VARCHAR(64) PRIMARY KEY, question VARCHAR(250) NOT NULL, answer TEXT NOT NULL, sort_order INT NOT NULL DEFAULT 0,
 active BOOLEAN NOT NULL DEFAULT TRUE, deleted_at DATETIME NULL, version INT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, event_key VARCHAR(200) UNIQUE NOT NULL, entity_type VARCHAR(30) NOT NULL, entity_id BIGINT NOT NULL,
 recipient VARCHAR(254) NOT NULL, subject VARCHAR(250) NOT NULL, body TEXT NOT NULL, status VARCHAR(30) NOT NULL DEFAULT 'pending',
 attempts INT NOT NULL DEFAULT 0, available_at DATETIME NOT NULL, locked_until DATETIME NULL,
 last_error VARCHAR(500) NULL, transport VARCHAR(20) NULL, sent_at DATETIME NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX queue (status,available_at), INDEX (entity_type,entity_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
