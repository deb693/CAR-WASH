CREATE TABLE IF NOT EXISTS reviews (
 id VARCHAR(64) PRIMARY KEY, author VARCHAR(100) NOT NULL, quote TEXT NOT NULL,
 rating INT NOT NULL, source_label VARCHAR(100) NOT NULL, source_url VARCHAR(500) NOT NULL,
 sort_order INT NOT NULL DEFAULT 0, active BOOLEAN NOT NULL DEFAULT TRUE,
 deleted_at DATETIME NULL, version INT NOT NULL DEFAULT 1,
 CHECK (rating BETWEEN 1 AND 5)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
